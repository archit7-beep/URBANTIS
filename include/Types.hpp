// Streaming Network Event Record
struct NetworkEvent {
    uint64_t timestamp{0};            // Simulation tick / second
    std::string sourceDeviceId;       // e.g. "GW-NORTH-01" or IP
    std::string targetDeviceId;       // e.g. "SIG-INT-04"
    CyberEventType type{CyberEventType::HEARTBEAT};
    uint32_t packetCount{1};
    uint64_t byteCount{64};
    int statusCode{200};              // HTTP/Protocol status code
    std::string payloadSignature;     // e.g. "AUTH_FAIL", "OVERRIDE_CMD", "SQL_INJ"
};

// Threat Alert generated by ThreatGraph Engine
struct CyberAlert {
    uint64_t alertId{0};
    uint64_t timestamp{0};
    double anomalyScore{0.0};         // e.g. Chi-squared score or burst multiplier
    double confidence{0.0};           // 0.0 to 1.0
    int severityLevel{1};             // 1 (Low) to 5 (Critical)
    std::string sourceDeviceId;
    std::string targetDeviceId;
    std::string category;             // e.g. "Microcluster DDoS", "Killchain Signature"
    std::string explanation;
    std::string evidenceChain;
    bool active{true};

    bool operator<(const CyberAlert& other) const {
        // High severity and high anomaly score first in priority queues
        if (severityLevel != other.severityLevel) {
            return severityLevel < other.severityLevel;
        }
        return anomalyScore < other.anomalyScore;
    }
};

