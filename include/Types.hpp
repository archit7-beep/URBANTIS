// Coordinates for geographic positioning in simulation grid (meters or normalized units)
struct Point2D {
    double x{0.0};
    double y{0.0};

    Point2D() = default;
    Point2D(double px, double py) : x(px), y(py) {}

    double distanceTo(const Point2D& other) const {
        double dx = x - other.x;
        double dy = y - other.y;
        return std::sqrt(dx * dx + dy * dy);
    }

    double manhattanTo(const Point2D& other) const {
        return std::abs(x - other.x) + std::abs(y - other.y);
    }
};

